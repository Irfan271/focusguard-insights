from datetime import datetime


def build_prediction_report(
    prediction,
    confidence,
    probabilities,
    inputs,
    recommendations,
):
    """
    Build the downloadable prediction report as plain text.
    """
    generated_at = datetime.now().astimezone().strftime(
        "%Y-%m-%d %H:%M:%S %Z"
    )

    report = f"""FocusGuard Insights — Prediction Report
Generated: {generated_at}

PREDICTION
----------
Predicted productivity: {prediction}
Model confidence: {confidence:.1%}

CLASS PROBABILITIES
-------------------
"""

    for class_name, probability in probabilities.items():
        report += f"{class_name}: {probability:.4f}\n"

    report += f"""
INPUT SUMMARY
-------------
App usage minutes: {inputs['usage_minutes']}
Sessions: {inputs['sessions']}
Notifications: {inputs['notifications']}
Study minutes: {inputs['study_minutes']}
Sleep hours: {inputs['sleep_hours']}
Hour of day: {inputs['hour_of_day']}
App category: {inputs['category']}
Total daily screen time: {inputs['daily_total_usage_minutes']} minutes
Total daily study time: {inputs['daily_study_minutes']} minutes
Weekend record: {'Yes' if inputs['is_weekend'] else 'No'}
Notifications per session: {inputs['notifications_per_session']}
Usage per session: {inputs['usage_per_session']}

RECOMMENDATIONS
---------------
"""

    for recommendation in recommendations:
        report += f"- {recommendation}\n"

    report += """
IMPORTANT LIMITATION
--------------------
This prediction is generated by a model trained on synthetic data.
The productivity labels were created from rules based on the same
features used for prediction, so the model's high evaluation scores
reflect label leakage rather than validated real-world predictive
performance.

Confidence represents the model's predicted probability for its chosen
label, not real-world certainty.

This report should not be used for medical, academic, employment, or
clinical decisions.
"""

    return report